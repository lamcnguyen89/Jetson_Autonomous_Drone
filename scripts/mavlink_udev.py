"""Generate a udev permissions rule for the configured MAVLink serial device."""

import argparse
from pathlib import Path
import re
import stat
import subprocess
import sys


def literal(value):
    """Accept literal identities without udev glob patterns or substitutions."""
    if not value or not re.fullmatch(r"[A-Za-z0-9_.:/@+ -]+", value):
        raise ValueError(f"Cannot safely match udev identity {value!r}")
    return value


def build_rule(device, properties):
    """Match a USB controller's identity or an onboard UART's fixed name."""
    # Scope permissions to the configured controller instead of granting the
    # service account access to every USB serial device connected to the host.
    if properties.get("SUBSYSTEM") != "tty":
        raise ValueError(f"{device} is not a tty serial device")

    matches = ['SUBSYSTEM=="tty"']
    is_usb = properties.get("ID_BUS") == "usb"
    if is_usb:
        matches.append('ENV{ID_BUS}=="usb"')
        for key in ("ID_VENDOR_ID", "ID_MODEL_ID"):
            value = properties.get(key, "")
            if not re.fullmatch(r"[0-9a-fA-F]{4}", value):
                raise ValueError(f"USB device is missing a valid {key}")
            matches.append(f'ENV{{{key}}}=="{value}"')

        serial = properties.get("ID_SERIAL_SHORT", "")
        # If no usable unique serial exists, bind to the physical USB port.
        if serial and re.fullmatch(r"[A-Za-z0-9_.:/@+ -]+", serial):
            matches.append(f'ENV{{ID_SERIAL_SHORT}}=="{serial}"')
        else:
            identity = literal(properties.get("ID_PATH", ""))
            matches.append(f'ENV{{ID_PATH}}=="{identity}"')

        interface = properties.get("ID_USB_INTERFACE_NUM", "")
        if interface:
            if not re.fullmatch(r"[0-9a-fA-F]{2}", interface):
                raise ValueError("USB device has an invalid interface number")
            matches.append(f'ENV{{ID_USB_INTERFACE_NUM}}=="{interface}"')
    else:
        # USB tty numbers can change; never fall back to a numbered USB match
        # when udev has not yet populated its persistent USB identity.
        if device.name.startswith(("ttyACM", "ttyUSB")):
            raise ValueError("USB identity is unavailable; reconnect the controller and retry")
        matches.append(f'KERNEL=="{literal(device.name)}"')

    return (
        "# Generated by Install_Auto_Drone.sh for the MAVLINK_PORT selection.\n"
        + ", ".join(matches + ['GROUP="dialout"', 'MODE="0660"']) + "\n"
    )


def inspect_port(port):
    """Inspect a serial device and return its safe persistent udev identity."""
    device = Path(port).resolve(strict=True)
    if device.parent != Path("/dev") or not stat.S_ISCHR(device.stat().st_mode):
        raise ValueError(f"{port} must resolve to a serial character device under /dev")
    result = subprocess.run(
        ["udevadm", "info", "--query=property", f"--name={device}"],
        check=True, capture_output=True, text=True,
    )
    properties = dict(
        line.split("=", 1) for line in result.stdout.splitlines() if "=" in line
    )
    return device, properties


def main():
    """Generate a persistent udev rule for the selected MAVLink serial device."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("port", help="MAVLINK_PORT from the project .env")
    parser.add_argument("output", type=Path, help="Generated .rules file")
    args = parser.parse_args()
    try:
        device, properties = inspect_port(args.port)
        args.output.write_text(build_rule(device, properties))
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"Cannot configure MAVLink permissions: {error}", file=sys.stderr)
        return 1
    print(f"Prepared MAVLink permissions for {args.port} -> {device}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
